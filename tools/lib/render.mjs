/**
 * Render a character file as a readable Markdown sheet.
 *
 * The Markdown is generated, never hand-edited: the JSON is the only source of
 * truth, so the two cannot drift apart.
 */

import { PROFICIENCY_BONUS, abilityMod, computeDerived, observedAsDerived } from "./rules.mjs";

function sign(value) {
  return value >= 0 ? `+${value}` : `${value}`;
}

function table(headers, rows) {
  const lines = [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ];
  return lines.join("\n");
}

export function renderMarkdown(character) {
  const { identity, build, proficiencies, features, inventory, observed } = character;
  const derived = computeDerived(character);
  const observedFlat = observedAsDerived(character);

  const out = [];

  out.push(`# ${character.name}`);
  out.push("");
  if (character.summary) {
    out.push(character.summary);
    out.push("");
  }

  out.push(`> Source of truth: \`character.json\`. Generated by \`npm run render\` - do not edit by hand.`);
  out.push("");

  out.push("## Identity");
  out.push("");
  out.push(
    table(
      ["Field", "Value"],
      [
        ["Ancestry", identity.ancestry],
        ["Heritage", identity.heritage ?? "-"],
        ["Background", identity.background ?? "-"],
        ["Class", identity.class],
        ["Archetype", identity.archetype ? `${identity.archetype.name} (${identity.archetype.level})` : "-"],
        ["Deity", identity.deity ?? "-"],
        ["Level", String(identity.level)],
        ["XP", `${identity.xp?.value ?? 0} / ${identity.xp?.max ?? 1000}`],
        ["Age", identity.age || "-"],
        ["Gender / pronouns", identity.gender || "-"],
        ["Ethnicity", identity.ethnicity || "-"],
        ["Nationality", identity.nationality || "-"],
        ["Languages", identity.languages.join(", ")],
      ],
    ),
  );
  out.push("");

  out.push("## Numbers");
  out.push("");
  const abilityRows = Object.entries(build.abilities).map(([key, ability]) => [
    key.toUpperCase(),
    String(ability.score),
    sign(abilityMod(ability.score)),
  ]);
  out.push(table(["Ability", "Score", "Mod"], abilityRows));
  out.push("");

  const statisticRows = [
    ["Armor class", "ac"],
    ["Fortitude", "fortitude"],
    ["Reflex", "reflex"],
    ["Will", "will"],
    ["Perception", "perception"],
    ["Initiative", "initiative"],
    ["Hit points", "hitPoints"],
  ].map(([label, key]) => {
    const value = key === "hitPoints" ? build.hp?.max : derived[key];
    const sheetValue = observedFlat[key];
    return [label, sign(value), sheetValue === undefined ? "-" : sign(sheetValue)];
  });
  for (const [name] of Object.entries(proficiencies.classDC ?? {})) {
    const value = derived[`classDC:${name}`];
    const sheetValue = observedFlat[`classDC:${name}`];
    statisticRows.push([`${name} class DC`, sign(value), sheetValue === undefined ? "-" : sign(sheetValue)]);
  }
  out.push(table(["Statistic", "Build", "Sheet"], statisticRows));
  out.push("");

  out.push(
    `Speed ${build.speed.land} ft. ${
      build.senses?.map((sense) => `${sense.name}${sense.range ? ` ${sense.range} ft` : ""}`).join(", ") ?? ""
    }`.trim(),
  );
  out.push("");

  out.push("## Skills");
  out.push("");
  const skillRows = Object.entries(proficiencies.skills ?? {})
    .filter(([name]) => name !== "lore")
    .map(([name, rank]) => {
      const value = derived[`skill:${name}`];
      const sheetValue = observedFlat[`skill:${name}`];
      return [
        name,
        rank,
        sign(PROFICIENCY_BONUS[rank] ?? 0),
        sign(value),
        sheetValue === undefined ? "-" : sign(sheetValue),
      ];
    });
  out.push(table(["Skill", "Rank", "Prof", "Build", "Sheet"], skillRows));
  out.push("");

  const loreEntries = Object.entries(proficiencies.skills?.lore ?? {});
  if (loreEntries.length > 0) {
    out.push(
      table(
        ["Lore", "Rank"],
        loreEntries.map(([name, rank]) => [name, rank]),
      ),
    );
    out.push("");
  }

  out.push("## Proficiencies");
  out.push("");
  out.push(
    table(
      ["Attacks", "Rank"],
      Object.entries(proficiencies.attacks ?? {}).map(([name, rank]) => [name, rank]),
    ),
  );
  out.push("");
  out.push(
    table(
      ["Defenses", "Rank"],
      Object.entries(proficiencies.defenses ?? {}).map(([name, rank]) => [name, rank]),
    ),
  );
  out.push("");

  out.push("## Features");
  out.push("");
  const featureGroups = [
    ["Ancestry", features.ancestry],
    ["Background", features.background],
    ["Class", features.class],
    ["Ancestry feats", features.ancestryFeats],
    ["Class feats", features.classFeats],
    ["Archetype feats", features.archetypeFeats],
    ["Skill feats", features.skillFeats],
    ["General feats", features.generalFeats],
    ["Bonus feats", features.bonusFeats],
  ];
  for (const [label, entries] of featureGroups) {
    if (!entries || entries.length === 0) continue;
    out.push(`### ${label}`);
    out.push("");
    for (const entry of entries) {
      const level = entry.level ? ` (level ${entry.level})` : "";
      out.push(`- **${entry.name}**${level}${entry.summary ? ` - ${entry.summary}` : ""}`);
    }
    out.push("");
  }

  const actionGroups = [
    ["Actions", character.actions?.actions],
    ["Reactions", character.actions?.reactions],
    ["Free actions", character.actions?.freeActions],
  ];
  out.push("## Actions");
  out.push("");
  for (const [label, entries] of actionGroups) {
    if (!entries || entries.length === 0) continue;
    out.push(`### ${label}`);
    out.push("");
    for (const entry of entries) {
      out.push(`- **${entry.name}**${entry.actionCost ? ` (${entry.actionCost})` : ""}${
        entry.summary ? ` - ${entry.summary}` : ""
      }`);
    }
    out.push("");
  }

  out.push("## Inventory");
  out.push("");
  out.push(
    table(
      ["Item", "Type", "Qty", "Bulk", "Equipped"],
      inventory.map((item) => [
        item.name,
        item.type,
        String(item.quantity ?? 1),
        String(item.bulk ?? 0),
        item.equipped ? "yes" : "no",
      ]),
    ),
  );
  out.push("");
  if (character.currency) {
    const currency = character.currency;
    out.push(
      `Currency ${currency.pp ?? 0} pp, ${currency.gp ?? 0} gp, ${currency.sp ?? 0} sp, ${
        currency.cp ?? 0
      } cp. Total wealth ${currency.totalWealthGp ?? 0} gp.`,
    );
    out.push("");
  }

  if (observed?.source) {
    out.push("---");
    out.push("");
    out.push(`Sheet values transcribed from: ${observed.source}`);
    out.push("");
  }

  return out.join("\n");
}
